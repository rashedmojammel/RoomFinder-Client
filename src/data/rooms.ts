export function getRoomBySlug(slug: string): Room | undefined {
  return rooms.find((room) => room.slug === slug || room.id === slug);
}

export function getRelatedRooms(currentId: string, area: string, limit = 3): Room[] {
  return rooms
    .filter((room) => room.id !== currentId)
    .sort((a, b) => (a.area === area ? -1 : 0) - (b.area === area ? -1 : 0))
    .slice(0, limit);
}